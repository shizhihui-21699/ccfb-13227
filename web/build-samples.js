#!/usr/bin/env node
// Builds web/samples.js from the samples/ tree so the page works from file://
// without fetch(). Also hashes app assets into a build stamp.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', 'samples');
const out = path.resolve(__dirname, '..', 'web', 'samples.js');

const META = {
  '01-reentrancy': { title: '重入 · 外部调用后改状态', desc: '银行取款与代付' },
  '02-unchecked': { title: '未检查返回值', desc: 'ETH 与 ERC20 转账' },
  '03-access': { title: '权限缺失', desc: '金库配置函数' },
  '04-randomness': { title: '区块随机数', desc: '抽奖开奖' },
  '05-integer': { title: '整数溢出与截断', desc: '代币计量' },
};

const groups = [];
for (const dir of fs.readdirSync(root).sort()) {
  const full = path.join(root, dir);
  if (!fs.statSync(full).isDirectory()) continue;
  const meta = META[dir] || { title: dir, desc: '' };
  const g = { id: dir, title: meta.title, desc: meta.desc, items: [] };
  for (const variant of ['vulnerable', 'fixed']) {
    const vdir = path.join(full, variant);
    if (!fs.existsSync(vdir)) continue;
    for (const f of fs.readdirSync(vdir).sort()) {
      if (!f.endsWith('.sol')) continue;
      const src = fs.readFileSync(path.join(vdir, f), 'utf8');
      g.items.push({
        id: `${dir}/${variant}/${f}`,
        name: f,
        variant,
        group: dir,
        src,
      });
    }
  }
  if (g.items.length) groups.push(g);
}

const body = `// Generated by web/build-samples.js — do not edit by hand.\nwindow.SOL_SAMPLES = ${JSON.stringify(groups, null, 2)};\n`;
fs.writeFileSync(out, body);
console.log(`wrote ${out}: ${groups.length} groups, ${groups.reduce((n, g) => n + g.items.length, 0)} files, ${(body.length / 1024).toFixed(1)} KiB`);
